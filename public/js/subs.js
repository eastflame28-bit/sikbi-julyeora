const BY_NEED = new Map(SUBSTITUTES.map((x) => [norm(x.need), x]));

export const SUB_CATS = [...new Set(SUBSTITUTES.map((x) => x.cat))];

// 레시피 재료 이름으로 사전 항목 찾기 (정확히 같은 이름 먼저, 없으면 이름 안에 들어 있는 것)
export function subEntry(name) {
  const n = norm(name);
  if (BY_NEED.has(n)) return BY_NEED.get(n);
  return SUBSTITUTES.find((x) => norm(x.need).length >= 2 && n.includes(norm(x.need))) || null;
}

// 내 재료로 대신할 수 있는 방법. 없으면 null
export function findSwap(name, pantryNames) {
  const entry = subEntry(name);
  if (!entry) return null;
  const opt = entry.options.find((op) => op.use.every((u) => hasIngredient(pantryNames, u)));
  return opt ? { ...opt, need: entry.need } : null;
}

// 사전 화면에서 '집에 있어요' 표시용
export function availableOptions(entry, pantryNames) {
  return entry.options.map((op) => ({ ...op, ok: op.use.every((u) => hasIngredient(pantryNames, u)) }));
}
